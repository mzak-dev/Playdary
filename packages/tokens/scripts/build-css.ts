import { writeFileSync } from "node:fs";
import { baseRadius, darkColors, fonts, lightColors, popShadow, radii, type ColorToken } from "../src/index.ts";

const kebab = (name: string) => name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);

const declarations = (colors: Partial<Record<ColorToken, string>>) =>
  Object.entries(colors).map(([name, value]) => `  --${kebab(name)}: ${value};`);

const darkRoot = [...declarations(darkColors), `  --pop-shadow: ${popShadow.dark};`, `  --radius: ${baseRadius};`];
const lightOverrides = [...declarations(lightColors), `  --pop-shadow: ${popShadow.light};`];

const themeInline = (font: { display: string; sans: string }) =>
  [
    ...Object.keys(darkColors).map((name) => `  --color-${kebab(name)}: var(--${kebab(name)});`),
    ...Object.entries(radii).map(([name, value]) => `  --radius-${name}: ${value};`),
    "  --shadow-pop: var(--pop-shadow);",
    `  --font-display: ${font.display};`,
    `  --font-sans: ${font.sans};`,
  ].join("\n");

const header = "/* Generated by scripts/build-css.ts from src/index.ts. Do not edit. */";

const web = `${header}

:root {
${darkRoot.join("\n")}
}

.light {
${lightOverrides.join("\n")}
}

@theme inline {
${themeInline(fonts.web)}
}
`;

const native = `${header}

:root {
${darkRoot.join("\n")}
}

@media (prefers-color-scheme: light) {
  :root {
${lightOverrides.map((line) => `  ${line}`).join("\n")}
  }
}

@theme inline {
${themeInline(fonts.native)}
}
`;

writeFileSync(new URL("../theme.css", import.meta.url), web);
writeFileSync(new URL("../theme.native.css", import.meta.url), native);
